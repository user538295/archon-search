"""macOS LaunchdSearchService — manages archon_search.server as a launchd daemon."""
from __future__ import annotations

import logging
import plistlib
import re
import shlex
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from xml.parsers.expat import ExpatError

from archon_search.paths import get_data_dir
from archon_search.platform.service import (
    _STOP_WAIT_TIMEOUT_S,
    SearchServiceLifecycle,
    ServiceStatus,
    get_secrets_env_file,
    write_errors_naming,
)

log = logging.getLogger(__name__)

_LABEL = "com.archon.search"

# The plist runs the wrapper script at background QoS: taskpolicy -b <wrapper>.
_TASKPOLICY_BACKGROUND = ("/usr/sbin/taskpolicy", "-b")
# Minimum seconds launchd waits before relaunching the KeepAlive job.
_THROTTLE_INTERVAL_S = 60
_WRAPPER_SCRIPT_NAME = "run-server.sh"
_WRAPPER_SCRIPT_MODE = 0o755
_LOG_FILE = Path("logs") / "archon-search.log"

# Each placeholder takes a shlex.quote()d value, so quotes, $, backticks and \ stay literal.
_WRAPPER_SCRIPT_TEMPLATE = """\
#!/bin/sh
# Auto-generated by archon-search. Do not edit.
[ -f {secrets_file} ] && {{ set -a; . {secrets_file}; set +a; }}
exec {python} -m archon_search.server
"""
# plistlib's XML format is always UTF-8; the wrapper is written as UTF-8 too.
_PLIST_ENCODING = "utf-8"
_WRAPPER_ENCODING = "utf-8"
# exec() and argv take C strings that end at NUL, so a path containing NUL cannot be passed on.
_NUL = "\x00"
# Noncharacters plistlib writes into the plist but its own XML parser cannot read back.
_PLIST_UNREADABLE_NONCHARACTERS = frozenset("\ufffe\uffff")
# C0 controls are U+0000..U+001F; the plist reads back only tab and newline among them (\r becomes \n).
_C0_CONTROL_END = 0x20
_PLIST_READABLE_C0_CONTROLS = frozenset("\t\n")


@dataclass(frozen=True)
class _ServicePaths:
    """The path values register() writes into the plist and the wrapper script it runs.

    The data directory is both the plist's WorkingDirectory and its ARCHON_SEARCH_DATA_DIR.
    The interpreter and the secrets file (the one the wizard writes) appear only in the wrapper.
    """

    data_dir: Path
    config_path: str
    python: str
    secrets_file: Path

    @property
    def wrapper(self) -> Path:
        return self.data_dir / _WRAPPER_SCRIPT_NAME

    @property
    def log_path(self) -> Path:
        return self.data_dir / _LOG_FILE


def _plist_round_trips(value: str) -> bool:
    """Whether a plist string holding ``value`` reads back as exactly ``value``.

    plistlib refuses the control characters XML 1.0 forbids (``ValueError``) and lone
    surrogates — a non-UTF-8 path byte decoded by ``os.fsdecode`` (``UnicodeEncodeError``,
    a ``ValueError``); it writes U+FFFE and U+FFFF but cannot read them back
    (``ExpatError``); and its writer rewrites a ``\\r`` as ``\\n``.
    CoreFoundation (``plutil``) reads tab, newline, DEL, C1 controls, ``&<>'"$`\\`` and non-ASCII
    back exactly as plistlib wrote them.
    """
    try:
        return plistlib.loads(plistlib.dumps(value)) == value
    except (ValueError, ExpatError):
        return False


def _plist_refusal_cause(value: str) -> str:
    """Name why the plist cannot carry ``value``, which ``_plist_round_trips`` already refused."""
    try:
        value.encode(_PLIST_ENCODING)
    except UnicodeEncodeError:
        return "that is not valid UTF-8"
    if _PLIST_UNREADABLE_NONCHARACTERS.intersection(value):
        return "containing U+FFFE or U+FFFF"
    if any(ord(char) < _C0_CONTROL_END and char not in _PLIST_READABLE_C0_CONTROLS for char in value):
        return "containing a C0 control character other than tab and newline"
    return "that would not read back unchanged"


def _check_plist_value(label: str, value: str) -> None:
    """Raise ``RuntimeError`` unless the plist carries ``value`` intact and the server reads it back unchanged.

    ``label`` carries its article.
    """
    if not _plist_round_trips(value):
        raise RuntimeError(f"launchd plist cannot hold {label} {_plist_refusal_cause(value)}: {value!r}")
    # The server strips ARCHON_SEARCH_CONFIG and ARCHON_SEARCH_DATA_DIR before using them.
    if value != value.strip():
        raise RuntimeError(f"archon-search would strip {label} with leading or trailing whitespace: {value!r}")


def _check_wrapper_value(label: str, value: str) -> None:
    """Raise ``RuntimeError`` unless the UTF-8 wrapper script can hold ``value`` (``label`` carries its article)."""
    if _NUL in value:
        raise RuntimeError(f"wrapper script cannot hold {label} containing NUL: {value!r}")
    try:
        value.encode(_WRAPPER_ENCODING)
    except UnicodeEncodeError:
        raise RuntimeError(f"wrapper script cannot hold {label} that is not valid UTF-8: {value!r}") from None


def _service_paths(config_path: str) -> _ServicePaths:
    """Return the path values register() writes for ``config_path``, unvalidated."""
    return _ServicePaths(
        data_dir=get_data_dir(),
        config_path=config_path,
        # sys.executable is '' or None when Python cannot determine it; refused by validation either way.
        python=sys.executable or "",
        secrets_file=get_secrets_env_file(),
    )


def _validated_service_paths(config_path: str) -> _ServicePaths:
    """Return ``_service_paths(config_path)``, raising ``RuntimeError`` for one the plist or wrapper cannot carry intact.

    The plist's wrapper and log paths are the data dir plus a fixed ASCII suffix, so its check covers them.
    """
    paths = _service_paths(config_path)
    _check_plist_value("a data directory", str(paths.data_dir))
    _check_plist_value("a config path", paths.config_path)
    if not paths.python:
        raise RuntimeError(f"wrapper script cannot exec an empty interpreter path: {sys.executable!r}")
    _check_wrapper_value("an interpreter path", paths.python)
    _check_wrapper_value("a secrets file path", str(paths.secrets_file))
    return paths


def _plist_content(paths: _ServicePaths) -> bytes:
    """Render the launchd job definition for ``paths`` as an XML plist (plistlib escapes every value)."""
    data_dir = str(paths.data_dir)
    log_path = str(paths.log_path)
    job = {
        "Label": _LABEL,
        "ProgramArguments": [*_TASKPOLICY_BACKGROUND, str(paths.wrapper)],
        "WorkingDirectory": data_dir,
        "EnvironmentVariables": {
            "ARCHON_SEARCH_CONFIG": paths.config_path,
            "ARCHON_SEARCH_DATA_DIR": data_dir,
        },
        "StandardOutPath": log_path,
        "StandardErrorPath": log_path,
        "KeepAlive": True,
        "RunAtLoad": True,
        "ThrottleInterval": _THROTTLE_INTERVAL_S,
    }
    return plistlib.dumps(job, fmt=plistlib.FMT_XML, sort_keys=False)


def _wrapper_content(paths: _ServicePaths) -> str:
    """Render the wrapper script for ``paths``, each value shell-quoted."""
    return _WRAPPER_SCRIPT_TEMPLATE.format(
        secrets_file=shlex.quote(str(paths.secrets_file)),
        python=shlex.quote(paths.python),
    )


class LaunchdSearchService(SearchServiceLifecycle):
    """Manages the archon-search server as a macOS launchd user agent."""

    @property
    def _plist_path(self) -> Path:
        return Path.home() / "Library" / "LaunchAgents" / "com.archon.search.plist"

    def _run(self, cmd: list[str]) -> subprocess.CompletedProcess[str]:
        return subprocess.run(cmd, capture_output=True, text=True)

    def _is_loaded(self) -> bool:
        try:
            result = self._run(["launchctl", "list", _LABEL])
            return result.returncode == 0
        except FileNotFoundError:
            return False

    def validate_registration(self, *, config_path: str) -> None:
        """Raise ``RuntimeError`` for a value the plist or the wrapper script cannot carry intact."""
        _validated_service_paths(config_path)

    def register(self, dry_run: bool = False, *, config_path: str) -> None:
        # register() is public and callable without replace_registration(), so it validates
        # too (defence in depth) — from the same values it renders, so what is checked is written.
        paths = _validated_service_paths(config_path)
        if dry_run:
            return
        plist_content = _plist_content(paths)
        wrapper_content = _wrapper_content(paths)

        with write_errors_naming(f"service files in {paths.data_dir}"):
            paths.data_dir.mkdir(parents=True, exist_ok=True)
            paths.wrapper.write_text(wrapper_content, encoding=_WRAPPER_ENCODING)  # noqa: durable-write
            paths.wrapper.chmod(_WRAPPER_SCRIPT_MODE)
            paths.log_path.parent.mkdir(parents=True, exist_ok=True)
        with write_errors_naming(str(self._plist_path)):
            self._plist_path.parent.mkdir(parents=True, exist_ok=True)
            self._plist_path.write_bytes(plist_content)  # noqa: durable-write

    def unregister(self, dry_run: bool = False) -> None:
        # Uninstall path — unlike stop(), this deliberately does NOT wait for the
        # process to go down (S04's /health-unreachable guarantee is a stop()
        # contract; uninstall then removes the plist and makes no such promise).
        if dry_run:
            return
        if self._is_loaded():
            try:
                result = self._run(["launchctl", "unload", str(self._plist_path)])
                if result.returncode != 0:
                    log.warning("launchctl unload failed (rc=%d): %s", result.returncode, result.stderr)
            except FileNotFoundError as exc:
                raise RuntimeError("launchctl binary not found") from exc
        if self._plist_path.exists():
            self._plist_path.unlink()
        wrapper = get_data_dir() / _WRAPPER_SCRIPT_NAME
        wrapper.unlink(missing_ok=True)

    def start(self, dry_run: bool = False) -> int:
        if dry_run:
            return 0
        if not self._plist_path.exists():
            raise RuntimeError(f"Plist not installed at {self._plist_path}")
        if self._is_loaded():
            return 0
        try:
            r1 = self._run(["launchctl", "load", str(self._plist_path)])
            if r1.returncode != 0:
                raise RuntimeError(f"launchctl load failed (rc={r1.returncode}): {r1.stderr}")
            r2 = self._run(["launchctl", "start", _LABEL])
            if r2.returncode != 0:
                raise RuntimeError(f"launchctl start failed (rc={r2.returncode}): {r2.stderr}")
        except FileNotFoundError as exc:
            raise RuntimeError("launchctl binary not found") from exc
        return 0

    def stop(self, dry_run: bool = False) -> int:
        if dry_run:
            return 0
        if not self._is_loaded():
            return 0
        try:
            result = self._run(["launchctl", "unload", str(self._plist_path)])
            if result.returncode != 0:
                raise RuntimeError(f"launchctl unload failed (rc={result.returncode}): {result.stderr}")
        except FileNotFoundError as exc:
            raise RuntimeError("launchctl binary not found") from exc
        # launchctl unload returns before the process has exited; wait for the
        # service to actually go down so /health is unreachable afterward (S04).
        # Return 0 only when confirmed down; 1 (with a WARNING) if the wait timed
        # out, so callers can distinguish a clean stop from a possibly-still-up one.
        if self._wait_until_stopped():
            return 0
        log.warning(
            "archon-search did not report stopped within %.0fs of unload; "
            "it may still be running",
            _STOP_WAIT_TIMEOUT_S,
        )
        return 1

    def status(self) -> ServiceStatus:
        try:
            result = self._run(["launchctl", "list", _LABEL])
        except FileNotFoundError:
            return ServiceStatus(running=False, pid=None, uptime_seconds=None)

        if result.returncode != 0:
            return ServiceStatus(running=False, pid=None, uptime_seconds=None)

        pid_match = re.search(r'"PID"\s*=\s*(\d+)', result.stdout)
        if not pid_match:
            return ServiceStatus(running=False, pid=None, uptime_seconds=None)

        try:
            pid = int(pid_match.group(1))
        except ValueError:
            return ServiceStatus(running=False, pid=None, uptime_seconds=None)

        if pid == 0:
            return ServiceStatus(running=False, pid=0, uptime_seconds=None)

        return ServiceStatus(running=True, pid=pid, uptime_seconds=None)
